def date_sanity(visit_date, visit_time=None, now: datetime | None = None,
                far_future_days: int = 60) -> dict | None:
    """
    فحص منطقية تاريخ/وقت الزيارة. بيرجّع dict فيه:
        level / message / choices / code
    """
    if not SERIOUS_WARNINGS:
        return None
    now = now or now_local()

    if isinstance(visit_date, datetime):
        visit_date = visit_date.date()
    if visit_date is None:
        return None

    dt = datetime.combine(visit_date, visit_time or time(12, 0))

    if dt < now - timedelta(minutes=30):
        return {
            "code": "past",
            "level": "blocker",
            "message": _pick(f"past|{visit_date}", PAST_MSGS) + "\n\n" + PAST_QUESTION,
            "choices": list(PAST_CHOICES),
        }

    days = (visit_date - now.date()).days
    if days > far_future_days:
        return {
            "code": "far_future",
            "level": "info",
            "message": _pick(f"far|{visit_date}", FAR_FUTURE_MSGS).format(days=days),
        }

    if visit_time:
        h = visit_time.hour
        if h >= 23 or h <= 3:
            disp = h if h <= 12 else h - 12
            return {
                "code": "late_night",
                "level": "info",
                "message": _pick(f"late|{h}", LATE_NIGHT_MSGS).format(h=disp),
            }
        if 4 <= h < 6:
            return {
                "code": "very_early",
                "level": "info",
                "message": _pick(f"early|{h}", VERY_EARLY_MSGS),
            }
    return None


