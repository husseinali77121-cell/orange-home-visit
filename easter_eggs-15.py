def render_caption(st, msg):
    """يعرض تعليق (أو أكتر) تحت الحقل مباشرة."""
    if not msg:
        return
    if isinstance(msg, str):
        msg = [msg]
    for m in msg:
        if m:
            st.caption(m)


def render_toast(st, msg, icon="🍊"):
    if msg:
        try:
            st.toast(msg, icon=icon)
        except Exception:
            st.success(msg)


