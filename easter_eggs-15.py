def client_comment(name: str = "", phone: str = "", tag: str = "",
                   age_years: int | None = None, age_unit: str = "سنة") -> list[str]:
    """تعليقات على بيانات العميل. بيرجّع list (ممكن تكون فاضية)."""
    out = []

    digits = "".join(ch for ch in str(phone or "") if ch.isdigit())
    if digits:
        n = len(digits)
        if n < 11:
            out.append(_pick("ph_short", PHONE_SHORT).format(n=n))
        elif n > 11:
            out.append(_pick("ph_long", PHONE_LONG).format(n=n))
        elif not digits.startswith("01"):
            out.append(_pick("ph_prefix", PHONE_PREFIX))
        elif len(set(digits[2:])) <= 2:
            out.append(_pick("ph_fake", PHONE_FAKE))

    clean   = (name or "").strip()
    started = bool(digits)
    if not clean:
        if started:
            out.append(_pick("nm_empty", NAME_EMPTY))
    elif len(clean) <= 2:
        out.append(_pick("nm_short", NAME_SHORT))
    elif len(clean.split()) == 1 and FUN_MODE:
        out.append(_pick("nm_one", NAME_ONE_WORD))

    if age_years is not None:
        if not age_years:
            if clean:
                out.append(_pick("age_empty", AGE_EMPTY))
        elif age_unit == "شهر" and 1 <= age_years <= 6:
            out.append(_pick("age_baby", AGE_BABY))
        elif age_unit == "سنة" and age_years > 120:
            out.append(_pick("age_weird", AGE_WEIRD))
        elif age_unit == "سنة" and age_years >= 90 and FUN_MODE:
            out.append(_pick("age_old", AGE_OLD))

    if FUN_MODE and tag:
        t = str(tag).upper()
        if "VIP" in t:
            out.append(_pick("tag_vip", TAG_VIP))
        elif "FREQUENT" in t or "متكرر" in tag:
            out.append(_pick("tag_freq", TAG_FREQUENT))
        elif "NEW" in t or "جديد" in tag:
            out.append(_pick("tag_new", TAG_NEW))

    return [m for m in out if m]


