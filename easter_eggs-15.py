    """تحية عند الدخول حسب نوع المستخدم والوقت. ثابتة طول الفترة."""
    if not FUN_MODE:
        return None
    conf = USER_GREETINGS.get(str(user_type or "").strip().lower())
    if not conf:
        return None
    now  = now_local()
    part = _day_part(now.hour)
    opts = conf.get(part) or conf.get("morning") or []
    if not opts:
        return None
    msg = _pick_daily(f"{user_type}|{now.date()}|{part}", opts)
    return msg.format(name=name or conf.get("name", ""))


