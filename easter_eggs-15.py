_ROTATION = 0


def set_rotation(token) -> None:
    """
    بيتنده مرة واحدة في أول الفورم برقم بيزيد مع كل فتحة.
    ده بيخلي كل موضع يمشي على قايمته بالترتيب (جملة ورا جملة)
    بدل الاختيار العشوائي اللي بيكرر نفسه.
    """
    global _ROTATION
    try:
        _ROTATION = int(token)
    except (TypeError, ValueError):
        _ROTATION = _stable_hash(str(token or ""))


def _stable_hash(text: str) -> int:
    """هاش ثابت بين التشغيلات — hash() المدمجة بتتغير كل مرة."""
    return int(hashlib.md5(text.encode("utf-8")).hexdigest()[:8], 16)


def _pick(seed, options):
    """
    تدوير حقيقي: كل فتحة فورم بتاخد الجملة اللي بعدها في القايمة،
    وبتلف من الأول بعد ما تخلص. وثابتة طول ما انت في نفس الفورم.
    كل موضع بيبدأ من نقطة مختلفة عشان ما يبقوش كلهم متزامنين.
    """
    if not options:
        return None
    return options[(_ROTATION + _stable_hash(str(seed))) % len(options)]


def _pick_daily(seed, options):
    """اختيار ثابت طول اليوم — للتحيات، مش بيتأثر بالتدوير."""
    if not options:
        return None
    return random.Random(str(seed)).choice(options)


